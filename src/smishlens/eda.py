"""Descriptive EDA for the UCI anchor, train split only.

Writes 8 labelled PNGs to ``reports/figures/`` and ``reports/eda.md`` with one
insight per figure. Every number in the markdown is computed here, never typed
by hand.

Usage: python -m smishlens.eda
"""

from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from smishlens.features import MetaFeatures  # noqa: E402
from smishlens.local_data import require_file  # noqa: E402
from smishlens.normalise import normalise  # noqa: E402

HAM = "#2b6cb0"
SPAM = "#c53030"
TOKEN = re.compile(r"\b[a-z][a-z']{1,}\b")
FIGS = Path("reports/figures")
MD = Path("reports/eda.md")


def _style() -> None:
    plt.rcParams.update(
        {
            "figure.dpi": 150,
            "savefig.dpi": 150,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.grid": True,
            "grid.alpha": 0.25,
            "font.size": 9,
            "axes.titlesize": 10,
            "axes.titleweight": "bold",
        }
    )


def _save(fig, name: str) -> None:
    fig.tight_layout()
    fig.savefig(FIGS / name, bbox_inches="tight")
    plt.close(fig)


def _tokens(text: str) -> list[str]:
    return TOKEN.findall(normalise(text))


def _logodds(df: pd.DataFrame, ngram: int, top: int = 20) -> pd.DataFrame:
    """Monroe et al. informative Dirichlet log-odds, z-scored."""
    spam = Counter()
    ham = Counter()
    for text, label in zip(df["text"], df["y"], strict=True):
        toks = _tokens(text)
        grams = toks if ngram == 1 else [f"{a} {b}" for a, b in zip(toks, toks[1:], strict=False)]
        (spam if label else ham).update(grams)
    vocab = set(spam) | set(ham)
    n_spam, n_ham = sum(spam.values()), sum(ham.values())
    alpha = 0.5
    rows = []
    for term in vocab:
        ys, yh = spam[term], ham[term]
        if ys + yh < 5:
            continue
        d = np.log((ys + alpha) / (n_spam + alpha * len(vocab))) - np.log(
            (yh + alpha) / (n_ham + alpha * len(vocab))
        )
        var = 1 / (ys + alpha) + 1 / (yh + alpha)
        rows.append({"term": term, "spam": ys, "ham": yh, "z": d / np.sqrt(var)})
    out = pd.DataFrame(rows).sort_values("z")
    return pd.concat([out.head(top), out.tail(top)])


def _logodds_fig(df: pd.DataFrame, ngram: int, name: str, title: str) -> pd.DataFrame:
    lo = _logodds(df, ngram)
    fig, ax = plt.subplots(figsize=(7, 5.2))
    colors = [SPAM if z > 0 else HAM for z in lo["z"]]
    ax.barh(lo["term"], lo["z"], color=colors)
    ax.axvline(0, color="black", lw=0.8)
    ax.set_xlabel("log-odds z-score  (negative = ham, positive = spam)")
    ax.set_title(title)
    _save(fig, name)
    return lo


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="EDA figures for the UCI anchor.")
    ap.add_argument("--train", default="data/processed/uci/train.csv")
    args = ap.parse_args(argv)
    require_file(args.train)
    _style()
    FIGS.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(args.train, encoding_errors="replace")
    df = df.dropna(subset=["text", "y"])
    y = df["y"].astype(int)
    spam, ham = df[y == 1], df[y == 0]
    meta = pd.DataFrame(
        MetaFeatures().transform(df["text"].tolist()), columns=MetaFeatures.NAMES
    )
    meta["y"] = y.to_numpy()
    lines = [
        "# EDA — UCI anchor (train split only)",
        "",
        f"Source: `{args.train}` — {len(df):,} rows "
        f"({len(spam):,} spam / {len(ham):,} ham, {y.mean():.3f} spam).",
        "The cal and test splits are not plotted. Every figure is regenerated by "
        "`python -m smishlens.eda`.",
        "",
    ]

    # 1 — balance
    fig, ax = plt.subplots(figsize=(5, 3))
    counts = [len(ham), len(spam)]
    bars = ax.bar(["ham", "spam"], counts, color=[HAM, SPAM])
    ax.bar_label(bars, fmt="%d")
    ax.set_ylabel("messages")
    ax.set_title("Class balance, train split")
    _save(fig, "fig01_balance.png")
    lines += [
        "## 1. Class balance",
        "![balance](figures/fig01_balance.png)",
        f"Insight: only {y.mean():.1%} of training messages are spam, so accuracy is "
        "uninformative and every model is scored on PR-AUC / recall at a fixed FPR.",
        "",
    ]

    # 2 — length
    fig, ax = plt.subplots(figsize=(6, 3))
    bins = np.logspace(0, np.log10(max(meta["n_chars"].max(), 10)), 40)
    ax.hist(meta.loc[meta.y == 0, "n_chars"], bins=bins, alpha=0.7, label="ham", color=HAM)
    ax.hist(meta.loc[meta.y == 1, "n_chars"], bins=bins, alpha=0.7, label="spam", color=SPAM)
    ax.set_xscale("log")
    ax.set_xlabel("characters (log scale)")
    ax.set_ylabel("messages")
    ax.legend()
    ax.set_title("Message length by class")
    _save(fig, "fig02_length.png")
    med_h, med_s = meta.loc[meta.y == 0, "n_chars"].median(), meta.loc[meta.y == 1, "n_chars"].median()
    lines += [
        "## 2. Message length",
        "![length](figures/fig02_length.png)",
        f"Insight: spam is longer at the median ({med_s:.0f} vs {med_h:.0f} chars), "
        "but the distributions overlap heavily — length alone separates little.",
        "",
    ]

    # 3 — digit ratio
    fig, ax = plt.subplots(figsize=(5, 3))
    data = [meta.loc[meta.y == 0, "digit_ratio"].clip(0, 0.5),
            meta.loc[meta.y == 1, "digit_ratio"].clip(0, 0.5)]
    parts = ax.violinplot(data, showmedians=True)
    for pc, c in zip(parts["bodies"], (HAM, SPAM), strict=True):
        pc.set_facecolor(c)
        pc.set_alpha(0.7)
    ax.set_xticks([1, 2], ["ham", "spam"])
    ax.set_ylabel("digit ratio (clipped at 0.5)")
    ax.set_title("Digit density by class")
    _save(fig, "fig03_digits.png")
    lines += [
        "## 3. Digit density",
        "![digits](figures/fig03_digits.png)",
        f"Insight: spam carries more digits (median {meta.loc[meta.y == 1, 'digit_ratio'].median():.3f} "
        f"vs {meta.loc[meta.y == 0, 'digit_ratio'].median():.3f}) — prices, shortcodes and "
        "phone numbers. The overlap means it is a supporting feature, not a rule.",
        "",
    ]

    # 4 — caps ratio
    fig, ax = plt.subplots(figsize=(5, 3))
    data = [meta.loc[meta.y == 0, "caps_ratio"], meta.loc[meta.y == 1, "caps_ratio"]]
    parts = ax.violinplot(data, showmedians=True)
    for pc, c in zip(parts["bodies"], (HAM, SPAM), strict=True):
        pc.set_facecolor(c)
        pc.set_alpha(0.7)
    ax.set_xticks([1, 2], ["ham", "spam"])
    ax.set_ylabel("uppercase share of letters")
    ax.set_title("Capitalisation by class")
    _save(fig, "fig04_caps.png")
    lines += [
        "## 4. Capitalisation",
        "![caps](figures/fig04_caps.png)",
        f"Insight: spam shouts more (median caps ratio "
        f"{meta.loc[meta.y == 1, 'caps_ratio'].median():.3f} vs "
        f"{meta.loc[meta.y == 0, 'caps_ratio'].median():.3f}), but many spam rows are "
        "lower-case, so casing is a weak prior rather than a reliable cue.",
        "",
    ]

    # 5 — URL presence
    fig, ax = plt.subplots(figsize=(5, 3))
    shares = [meta.loc[meta.y == 0, "has_url"].mean() * 100, meta.loc[meta.y == 1, "has_url"].mean() * 100]
    bars = ax.bar(["ham", "spam"], shares, color=[HAM, SPAM])
    ax.bar_label(bars, fmt="%.1f%%")
    ax.set_ylabel("% of messages with a URL")
    ax.set_ylim(0, max(shares) * 1.35 + 1)
    ax.set_title("URL presence by class")
    _save(fig, "fig05_url.png")
    lines += [
        "## 5. URL presence",
        "![url](figures/fig05_url.png)",
        f"Insight: URLs are rare in both classes ({shares[0]:.1f}% of ham, "
        f"{shares[1]:.1f}% of spam). The anchor cannot support strong claims about "
        "link-based detection; that experiment belongs to the modern pool.",
        "",
    ]

    # 6 — punctuation / money / phone
    fig, ax = plt.subplots(figsize=(6, 3))
    cues = {
        "'!' present": (meta["n_excl"] > 0),
        "currency symbol": (meta["n_currency"] > 0),
        "phone-like number": (meta["has_phone"] > 0),
        "shortcode (5-6 digits)": (meta["has_shortcode"] > 0),
    }
    width = 0.38
    xs = np.arange(len(cues))
    ham_pct = [100 * (v[meta.y == 0].mean()) for v in cues.values()]
    spam_pct = [100 * (v[meta.y == 1].mean()) for v in cues.values()]
    ax.bar(xs - width / 2, ham_pct, width, label="ham", color=HAM)
    ax.bar(xs + width / 2, spam_pct, width, label="spam", color=SPAM)
    ax.set_xticks(xs, list(cues), rotation=15, ha="right")
    ax.set_ylabel("% of messages")
    ax.legend()
    ax.set_title("Surface cues by class")
    _save(fig, "fig06_cues.png")
    lines += [
        "## 6. Surface cues",
        "![cues](figures/fig06_cues.png)",
        f"Insight: currency symbols and shortcodes are almost exclusive to spam "
        f"({spam_pct[1]:.1f}% vs {ham_pct[1]:.1f}% for currency; "
        f"{spam_pct[3]:.1f}% vs {ham_pct[3]:.1f}% for shortcodes), while '!' is much more "
        f"common in spam ({spam_pct[0]:.1f}% vs {ham_pct[0]:.1f}%) yet still appears in "
        "roughly one ham message in eight, so it is a weak cue on its own.",
        "",
    ]

    # 7 — log-odds words
    lo_w = _logodds_fig(df, 1, "fig07_logodds_words.png", "Log-odds words (top 20 per class)")
    lines += [
        "## 7. Log-odds words",
        "![words](figures/fig07_logodds_words.png)",
        f"Insight: the spam side is dominated by offer mechanics "
        f"({', '.join(lo_w.tail(5)['term'].tolist())}); the ham side by conversational "
        f"fillers ({', '.join(lo_w.head(5)['term'].tolist())}). These are corpus-era cues, "
        "not stable smishing signals — a reason to validate on the modern pool.",
        "",
    ]

    # 8 — log-odds bigrams
    lo_b = _logodds_fig(df, 2, "fig08_logodds_bigrams.png", "Log-odds bigrams (top 20 per class)")
    lines += [
        "## 8. Log-odds bigrams",
        "![bigrams](figures/fig08_logodds_bigrams.png)",
        f"Insight: bigrams expose campaign templates on the spam side "
        f"({', '.join(lo_b.tail(4)['term'].tolist())}) and social phrasing on the ham side "
        f"({', '.join(lo_b.head(4)['term'].tolist())}); the `lt gt` term is an unescaped "
        "HTML-entity artefact in the corpus, not language. This is why word 1-2 grams are "
        "in the production feature set.",
        "",
    ]

    MD.write_text("\n".join(lines))
    print(f"wrote 8 figures to {FIGS} and {MD}")


if __name__ == "__main__":
    main()
